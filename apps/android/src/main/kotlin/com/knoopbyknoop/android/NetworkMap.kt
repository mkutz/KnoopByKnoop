  /** Whether the map moves to the rider with the next position, e.g. after the app was opened. */
  var findRider = false

  /**
   * Shows the rider and the next knot; when navigation begins or the app is opened while
   * navigating, the map moves to the rider, see `knot-navigation` "Looking at the map".
   */
  /**
   * Whether the map follows the rider while navigating, see `knot-navigation` "Following the
   * rider": from the start of navigation until the user moves the map, and again after [recenter].
   */
  var following by mutableStateOf(false)

  private var direction: Double? = null

  fun showNavigation(
    newPosition: Fix?,
    newNextKnot: Knot?,
    newWayToRoute: GeoPoint? = null,
    newDirection: Double? = null,
    newGuidedWay: List<GeoPoint>? = null,
  ) {
    val begins = newPosition != null && (position == null || findRider)
    if (begins) {
      findRider = false
      following = true
    }
    if (newPosition == null) following = false
    position = newPosition
    nextKnot = newNextKnot
    wayToRoute = newWayToRoute
    guidedWay = newGuidedWay
    direction = newDirection
    style?.let { updateNavigation(it) }
    if (newPosition == null || !following) return
    val map = map ?: return
    val rider = LatLng(newPosition.latitude, newPosition.longitude)
    if (newWayToRoute != null) {
      // Off route, the rider and the end of the way back, so they see where the route is.
      val bounds =
        LatLngBounds.Builder()
          .include(rider)
          .include(LatLng(newWayToRoute.latitude, newWayToRoute.longitude))
          .build()
      // Below the controls at the top, and no closer than following, as the way back can be short.
      val camera = map.getCameraForLatLngBounds(bounds, intArrayOf(160, compassTop + 160, 160, 160))
      if (camera != null) {
        // One even move per fix too, or the labels flicker as they do while following, see below.
        map.easeCamera(
          CameraUpdateFactory.newCameraPosition(
            CameraPosition.Builder(camera).zoom(minOf(camera.zoom, NAVIGATION_ZOOM)).build()
          ),
          FOLLOW_MOVE_MILLIS,
          false,
        )
      }
    } else if (begins) {
      map.animateCamera(
        CameraUpdateFactory.newLatLngZoom(rider, maxOf(map.cameraPosition.zoom, NAVIGATION_ZOOM))
      )
    } else {
      // One even move per fix, as long as the time to the next one: an animation restarted with
      // every fix makes the base map place its labels anew all the time, so they flicker, see
      // `knot-navigation` "Following the rider".
      map.easeCamera(CameraUpdateFactory.newLatLng(rider), FOLLOW_MOVE_MILLIS, false)
    }
  }

