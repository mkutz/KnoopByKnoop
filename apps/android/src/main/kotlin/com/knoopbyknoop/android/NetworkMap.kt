/**
 * The map with the network and the route, and buttons to zoom. Taps are reported with the touch
 * target in meters at the current zoom level, so the core's knot locator can pick the knot.
 *
 * The map is shown before a network is loaded ([graph] and [layers] `null`), at [initialPlace] if
 * there is one, see `map-planning` "Map, knots and courses one after the other".
 */
@Composable
fun NetworkMap(
  graph: NetworkGraph?,
  layers: MapLayers?,
  focus: List<Knot>,
  onTap:
    (
      latitude: Double,
      longitude: Double,
      radiusMeters: Double,
      x: Float,
      y: Float,
      place: MapPlace?,
    ) -> Unit,
  online: Boolean,
  initialPlace: CameraPlace?,
  onLeave: (CameraPlace) -> Unit,
  marker: PlaceHit?,
  onMove: (CameraPlace, GeoBounds?) -> Unit,
  modifier: Modifier = Modifier,
  /** The rider's position while navigating, see `knot-navigation` "Position on the map". */
  position: Fix? = null,
  /** The track ridden while navigating, see `knot-navigation` "Ridden track". */
  track: RiddenTrack? = null,
  /** The riding direction, see `knot-navigation` "Riding direction on the map". */
  direction: Double? = null,
  /** The next knot while navigating, highlighted. */
  nextKnot: Knot? = null,
  /** Whether navigation has begun, so the route is calm, see `knot-navigation` "Leg ahead". */
  navigating: Boolean = false,
  /** The course to the next knot, see `knot-navigation` "Leg ahead on the map". */
  courseAhead: List<GeoPoint>? = null,
  /**
   * Off route, where the line back to the route ends, see `knot-navigation` "Way to the route on
   * the map"; `null` on the route.
   */
  wayToRoute: GeoPoint? = null,
  /** Off route, the way along paths, see `knot-navigation` "Guided way back to the route". */
  guidedWay: List<GeoPoint>? = null,
  /** The position found on request while planning, see `map-planning` "Show my position". */
  myPosition: Fix? = null,
  /** Whether the position is being found. */
  locating: Boolean = false,
  /** Asks for the position; `null` while navigating, which hides the button. */
  onLocate: (() -> Unit)? = null,
  /** Whether the nearest knots are being found. */
  findingNearest: Boolean = false,
  /** Shows the nearest knots; `null` while knots are in view, which hides the button. */
  onShowNearest: (() -> Unit)? = null,
  /** Where to move for the nearest knots, until [onNearestShown]. */
  nearestKnots: NearestKnots? = null,
  onNearestShown: () -> Unit = {},
  /** A coming knot to show while navigating, see `knot-navigation` "Showing a coming knot". */
  shownKnot: ShownKnot? = null,
  /**
   * A tapped place offered as a route point, marked with a flag, see `map-planning` "Choose a route
   * point on the map".
   */
  offerPlace: GeoPoint? = null,
  /** Whether [offerPlace] gets its flag; not for a place whose name only is shown. */
  offerFlag: Boolean = true,
  /** Called with where [offerPlace] is on the map, in pixels, while the map moves. */
  onOfferMoved: (x: Float, y: Float) -> Unit = { _, _ -> },
  /**
   * Where the controls at the top of the map end, in pixels from its top, and where they start,
   * from its start, so the compass shows below them, see `map-planning` "Clear of the system bars".
   */
  topControlsBottom: Int = 0,
  topControlsStart: Int = 0,
  /**
   * Holds back a change of the appearance until this is `false` again, e.g. while the info sheet is
   * open.
   */
  holdAppearance: Boolean = false,
  /**
   * Whether places useful on a ride are highlighted, see `map-planning` "Places useful on a ride".
   */
  places: Boolean = true,
) {
  val context = LocalContext.current
  val touchTargetPixels = with(LocalDensity.current) { TOUCH_TARGET_DP * density }
  val holder = remember { MapHolder() }
  holder.density = LocalDensity.current.density
  val dark = isAppInDarkTheme()
  holder.dark = dark
  holder.online = online
  holder.placeIcons = remember {
    PlaceKind.entries.associate { it.iconName to placeBitmap(it) }
  }
  val mapView = remember {
    MapLibre.getInstance(context)
    // Before any style is loaded, the map shows the offline style's background, not MapLibre's.
    val options =
      MapLibreMapOptions.createFromAttributes(context)
        .foregroundLoadColor(if (dark) OFFLINE_DARK_BACKGROUND else OFFLINE_LIGHT_BACKGROUND)
    MapView(context, options).apply {
      onCreate(null)
      addOnDidFinishRenderingFrameListener { _, _, _ -> holder.markVisibleLayers(width, height) }
      getMapAsync { map ->
        holder.map = map
        holder.placeCompass()
        map.addOnCameraIdleListener { holder.place()?.let { holder.onMove(it, holder.knotArea()) } }
        // The offered place's choices stay at its flag while the map moves.
        map.addOnCameraMoveListener { holder.reportOffer() }
        // Moving or zooming the map by hand stops following the rider; the app's own camera moves
        // don't.
        map.addOnCameraMoveStartedListener { reason ->
          if (reason == MapLibreMap.OnCameraMoveStartedListener.REASON_API_GESTURE) {
            holder.following = false
          }
        }
        map.addOnMapClickListener { point ->
          if (map.cameraPosition.zoom < KNOT_MIN_ZOOM) {
            // Zoomed out, knots are not shown: a tap on the route zooms to it.
            val screenPoint = map.projection.toScreenLocation(point)
            val area =
              RectF(
                screenPoint.x - touchTargetPixels,
                screenPoint.y - touchTargetPixels,
                screenPoint.x + touchTargetPixels,
                screenPoint.y + touchTargetPixels,
              )
            if (map.queryRenderedFeatures(area, "route").isNotEmpty()) holder.zoomToFocus()
            return@addOnMapClickListener true
          }
          val metersPerPixel = map.projection.getMetersPerPixelAtLatitude(point.latitude)
          val screenPoint = map.projection.toScreenLocation(point)
          holder.onTap(
            point.latitude,
            point.longitude,
            metersPerPixel * touchTargetPixels,
            screenPoint.x,
            screenPoint.y,
            holder.placeAt(screenPoint.x, screenPoint.y, touchTargetPixels),
          )
          true
        }
        initialPlace?.let {
          map.moveCamera(
            CameraUpdateFactory.newLatLngZoom(LatLng(it.latitude, it.longitude), it.zoom)
          )
          holder.hasPlace = true
        }
        addOnDidFailLoadingMapListener { holder.useOfflineStyle() }
        if (online) {
          holder.loadBaseMap()
          postDelayed(
            {
              if (!holder.hasStyle) {
                holder.useOfflineStyle()
                postDelayed(
                  { if (holder.usesOfflineStyle && holder.online) holder.loadBaseMap() },
                  BASE_MAP_RETRY_MILLIS,
                )
              }
            },
            BASE_MAP_TIMEOUT_MILLIS,
          )
        } else {
          // Offline, MapLibre would wait for the base map, and nothing can be drawn without a
          // style.
          holder.useOfflineStyle()
        }
      }
    }
  }
  holder.onTap = onTap
  holder.onMove = onMove
  holder.show(graph, layers, focus)
  // A chosen search hit: the map moves there, close enough to tap knots, see `place-search`.
  LaunchedEffect(marker) { holder.showMarker(marker) }
  holder.onOfferMoved = onOfferMoved
  LaunchedEffect(offerPlace, offerFlag) { holder.showOffer(offerPlace, offerFlag) }
  LaunchedEffect(myPosition) {
    holder.showMyPosition(myPosition, center = myPosition != nearestKnots?.rider)
  }
  LaunchedEffect(nearestKnots) {
    nearestKnots?.let {
      holder.showNearestKnots(it)
      onNearestShown()
    }
  }
  LaunchedEffect(position, nextKnot, wayToRoute, guidedWay) {
    holder.showNavigation(position, nextKnot, wayToRoute, direction, guidedWay)
  }
  LaunchedEffect(track) { holder.showTrack(track) }
  LaunchedEffect(navigating, courseAhead, layers?.geometry) {
    holder.showLegAhead(navigating, courseAhead, layers?.geometry)
  }
  LaunchedEffect(topControlsBottom, topControlsStart) {
    holder.compassTop = topControlsBottom
    holder.compassStart = topControlsStart
    holder.placeCompass()
  }
  LaunchedEffect(places) { holder.showPlaces(places) }
  LaunchedEffect(shownKnot) { shownKnot?.let { holder.showKnot(it.knot) } }
  // The offline style has no base map; it is loaded as soon as network access is back.
  LaunchedEffect(online) { if (online && holder.usesOfflineStyle) holder.loadBaseMap() }
  // Switched in place, the camera stays, see `map-planning` "Switching while the app is open".
  LaunchedEffect(dark, holdAppearance) {
    if (!holdAppearance) holder.reloadStyleIfAppearanceChanged()
  }

  val lifecycle = LocalLifecycleOwner.current.lifecycle
  DisposableEffect(lifecycle) {
    val observer = LifecycleEventObserver { _, event ->
      when (event) {
        Lifecycle.Event.ON_START -> {
          mapView.onStart()
          holder.findRider = true
        }
        Lifecycle.Event.ON_RESUME -> mapView.onResume()
        Lifecycle.Event.ON_PAUSE -> mapView.onPause()
        Lifecycle.Event.ON_STOP -> {
          holder.place()?.let(onLeave)
          mapView.onStop()
        }
        else -> {}
      }
    }
    lifecycle.addObserver(observer)
    onDispose {
      lifecycle.removeObserver(observer)
      mapView.onDestroy()
    }
  }

  Box(modifier = modifier) {
    AndroidView(factory = { mapView })
    Column(modifier = Modifier.align(Alignment.CenterEnd).padding(12.dp)) {
      listOf("+" to 1.0, "−" to -1.0).forEach { (label, delta) ->
        SmallFloatingActionButton(
          onClick = { holder.zoomBy(delta) },
          containerColor = mapOverlayColor,
          contentColor = Green,
          modifier = Modifier.padding(vertical = 4.dp),
        ) {
          Text(label, fontSize = 22.sp)
        }
      }
      // While planning: the rider's position once per tap, see `map-planning` "Show my position".
      if (onLocate != null) {
        SmallFloatingActionButton(
          onClick = onLocate,
          containerColor = mapOverlayColor,
          contentColor = Green,
          modifier = Modifier.padding(top = 12.dp),
        ) {
          if (locating)
            CircularProgressIndicator(modifier = Modifier.size(20.dp), strokeWidth = 2.dp)
          else
            Icon(
              painterResource(R.drawable.ic_my_position),
              contentDescription = stringResource(R.string.my_position),
            )
        }
      }
      // Only while planning with no knots in view, see `map-planning` "Nearest knots".
      if (onShowNearest != null) {
        SmallFloatingActionButton(
          onClick = onShowNearest,
          containerColor = mapOverlayColor,
          contentColor = Green,
          modifier = Modifier.padding(top = 12.dp),
        ) {
          if (findingNearest)
            CircularProgressIndicator(modifier = Modifier.size(20.dp), strokeWidth = 2.dp)
          else
            Icon(
              painterResource(R.drawable.ic_nearest_knots),
              contentDescription = stringResource(R.string.show_nearest_knots),
            )
        }
      }
      // Only while navigating and after the user moved the map away from the rider.
      if (position != null && !holder.following) {
        SmallFloatingActionButton(
          onClick = holder::recenter,
          containerColor = ActionColors.green,
          contentColor = Color.White,
          modifier = Modifier.padding(top = 12.dp),
        ) {
          Icon(
            painterResource(R.drawable.ic_action_recenter),
            contentDescription = stringResource(R.string.recenter),
          )
        }
      }
    }
  }
}

/** Keeps the map, its style and what is shown, so updates only touch what changed. */
private class MapHolder {
  var map: MapLibreMap? = null

  /** The display density, to size the rider's arrow in dp. */
  var density = 1f

  /** The compass's margins from the map's top and start, in pixels. */
  var compassTop = 0
  var compassStart = 0

  /**
   * Below the controls at the top, at the start, so it covers neither them, the status bar nor the
   * zoom buttons at the end, which reach up to it in landscape.
   */
  fun placeCompass() {
    val settings = map?.uiSettings ?: return
    settings.compassGravity = Gravity.TOP or Gravity.START
    settings.setCompassMargins(compassStart, compassTop, 0, 0)
  }

  var onTap: (Double, Double, Double, Float, Float, MapPlace?) -> Unit = { _, _, _, _, _, _ -> }
  private var style: Style? = null

  /** Whether a style is loaded, the base map or the offline style. */
  val hasStyle: Boolean
    get() = style != null

  var usesOfflineStyle = false
    private set

  /** Whether the system is in dark mode; the next style loaded follows it. */
  var dark = false

  /** Whether the device has network access, to load the base map again after falling back. */
  var online = false

  /** The appearance of the loaded style, to see whether it still matches [dark]. */
  private var styleDark: Boolean? = null

  private var graph: NetworkGraph? = null
  private var layers: MapLayers? = null
  private var focus: List<Knot> = listOf()
  private var shownGraph: NetworkGraph? = null
  private var shownLayers: MapLayers? = null

  fun loadBaseMap() {
    val loadingDark = dark
    forgetStyle()
    map?.setStyle(
      Style.Builder().fromUri(if (loadingDark) DARK_BASE_MAP_STYLE else BASE_MAP_STYLE)
    ) {
      usesOfflineStyle = false
      styleDark = loadingDark
      onStyle(it)
    }
  }

  fun useOfflineStyle() {
    val loadingDark = dark
    forgetStyle()
    map?.setStyle(Style.Builder().fromJson(offlineStyle(loadingDark))) {
      usesOfflineStyle = true
      styleDark = loadingDark
      onStyle(it)
    }
  }

  /**
   * MapLibre invalidates a style as soon as the next one starts loading; until that one is loaded,
   * updates wait for [onStyle], which adds everything again.
   */
  private fun forgetStyle() {
    style = null
  }

  /** Loads the same kind of style, base map or offline, again when the appearance changed. */
  fun reloadStyleIfAppearanceChanged() {
    val loaded = styleDark ?: return
    if (loaded == dark) return
    if (usesOfflineStyle) useOfflineStyle() else loadBaseMap()
  }

  private var coursesHandedOver = false

  /**
   * Called after every rendered frame until the knots and the courses are visible: MapLibre parses
   * large layers on its own, so they show up some time after they were handed over.
   */
  fun markVisibleLayers(width: Int, height: Int) {
    val map = map ?: return
    if (StartupMarks.isMarked("courses")) return
    val screen = RectF(0f, 0f, width.toFloat(), height.toFloat())
    if (map.queryRenderedFeatures(screen, "knots").isNotEmpty()) StartupMarks.mark("knots")
    if (coursesHandedOver && map.queryRenderedFeatures(screen, "connections").isNotEmpty()) {
      StartupMarks.mark("courses")
    }
  }

  private fun onStyle(loaded: Style) {
    StartupMarks.mark("map")
    style = loaded
    shownLayers = null
    // The appearance may have changed again while this style was loading.
    if (styleDark != dark) {
      reloadStyleIfAppearanceChanged()
      return
    }
    addLayers(loaded)
    placesFilters = mapOf()
    updatePlaces(loaded)
    updateMarker(loaded)
    updateOffer(loaded)
    updateNavigation(loaded)
    updateTrack(loaded)
    updateLegAhead(loaded)
    update()
  }

  /**
   * Adds the bridges over the route when the shown geometry has bridge stretches, and takes them
   * away when it has none, see `map-planning` "Route and bridges": semi-transparent copies of the
   * base map's bridge layers, then the stretches of the lines that run on a bridge on top of them,
   * all below the ridden track, which stays visible on a bridge. The offline style has no bridge
   * layers, so nothing is copied there.
   */
  private fun updateBridges(style: Style) {
    val wanted = layers?.geometry?.hasBridges == true
    val present = style.getLayer(BRIDGE_LINES.first().second) != null
    if (wanted == present) return
    if (!wanted) {
      style.layers
        .filter {
          it.id.endsWith(BRIDGE_COPY_SUFFIX) ||
            it.id.endsWith(BRIDGE_EDGES_SUFFIX) ||
            BRIDGE_LINES.any { (_, id) -> id == it.id }
        }
        .forEach { style.removeLayer(it) }
      return
    }
    val bridges = style.layers.filter(::isBaseMapBridge).filterIsInstance<LineLayer>()
    if (bridges.isEmpty()) return
    for (bridge in bridges) {
      style.addLayerBelow(
        copyOf(bridge, bridge.id + BRIDGE_COPY_SUFFIX, bridge.sourceId, bridge.sourceLayer).apply {
          bridge.filter?.let { setFilter(it) }
          setProperties(PropertyFactory.lineOpacity(BRIDGE_OPACITY))
        },
        "ridden-track",
      )
    }
    // The edges of a bridge where the route runs on one, see `map-planning` "Bridge edges on the
    // route".
    for ((original, width) in listOf("route" to ROUTE_WIDTH, "route-ahead" to ROUTE_WIDTH_AHEAD)) {
      val line = style.getLayerAs<LineLayer>(original) ?: continue
      val onBridge = Expression.eq(Expression.get("bridge"), true)
      style.addLayerBelow(
        LineLayer(original + BRIDGE_EDGES_SUFFIX, line.sourceId).apply {
          setFilter(line.filter?.let { Expression.all(it, onBridge) } ?: onBridge)
          setProperties(
            PropertyFactory.lineColor(
              if (styleDark == true) BRIDGE_EDGE_DARK else BRIDGE_EDGE_LIGHT
            ),
            PropertyFactory.lineOpacity(BRIDGE_EDGE_OPACITY),
            PropertyFactory.lineWidth(BRIDGE_EDGE_WIDTH),
            PropertyFactory.lineGapWidth(width + 2f),
            PropertyFactory.lineOffset(ROUTE_OFFSET),
          )
        },
        "ridden-track",
      )
    }
    for ((original, id) in BRIDGE_LINES) {
      val line = style.getLayerAs<LineLayer>(original) ?: continue
      val onBridge = Expression.eq(Expression.get("bridge"), true)
      style.addLayerBelow(
        copyOf(line, id, line.sourceId, null).apply {
          setFilter(line.filter?.let { Expression.all(it, onBridge) } ?: onBridge)
        },
        "ridden-track",
      )
    }
  }

  /** A line layer drawn like [layer], from the same source, with the id [id]. */
  private fun copyOf(layer: LineLayer, id: String, sourceId: String, sourceLayer: String?) =
    LineLayer(id, sourceId).apply {
      sourceLayer?.let { withSourceLayer(it) }
      minZoom = layer.minZoom
      maxZoom = layer.maxZoom
      val properties =
        listOf(
            layer.lineColor,
            layer.lineWidth,
            layer.lineGapWidth,
            layer.lineOffset,
            layer.lineOpacity,
            layer.lineDasharray,
            layer.lineCap,
            layer.lineJoin,
          )
          .filter { !it.isNull }
          .map { value ->
            if (value.isExpression) PropertyValue(value.name, value.expression)
            else PropertyValue(value.name, value.value)
          }
      setProperties(*properties.toTypedArray())
    }

