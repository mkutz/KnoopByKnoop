  private fun update() {
    val style = style ?: return
    val layers = layers ?: return
    updateBridges(style)
    val previous = shownLayers
    if (
      previous == null ||
        previous.knots !== layers.knots ||
        previous.connections !== layers.connections
    ) {
      // Grey on the light map, dark on the dark map; a new style comes with no images.
      val knotsDark = styleDark == true
      layers.refs.forEach { ref ->
        val name = badgeName(null, ref)
        if (style.getImage(name) == null) {
          style.addImage(name, badgeBitmap(null, ref, dark = knotsDark))
        }
      }
      style.getSourceAs<GeoJsonSource>("knots")?.setGeoJson(layers.knots)
      style.getSourceAs<GeoJsonSource>("connections")?.setGeoJson(layers.connections)
      coursesHandedOver = layers.hasCourses
    }
    if (previous == null || previous.route !== layers.route) {
      layers.routeKnotList.forEach { (knot, role) ->
        val plate = KnotPlate.of(knot.signRegion)
        val place = knot.routePoint?.placeKind
        val name = badgeName(role, knot.ref, plate, place)
        if (style.getImage(name) == null) {
          style.addImage(name, badgeBitmap(role, knot.ref, plate, place = place))
        }
      }
      style.getSourceAs<GeoJsonSource>("route")?.setGeoJson(layers.route)
      style.getSourceAs<GeoJsonSource>("route-knots")?.setGeoJson(layers.routeKnots)
      style.getSourceAs<GeoJsonSource>("route-point-ways")?.setGeoJson(layers.routePointWays)
    }
    shownLayers = layers
    if (shownGraph !== graph) {
      // The map keeps its place: the one saved when the app was left, or the one before switching
      // to another network. Without one, it shows the route if there is one, or the network's
      // center. Either way knots must be shown, see `map-planning`.
      val currentGraph = graph
      when {
        hasPlace -> {}
        focus.size >= 2 -> fitTo(focus, animated = false)
        currentGraph != null -> fitTo(currentGraph.knots.values, animated = false)
      }
      hasPlace = true
      map?.let {
        if (it.cameraPosition.zoom < KNOT_MIN_ZOOM)
          it.moveCamera(CameraUpdateFactory.zoomTo(KNOT_MIN_ZOOM))
      }
      shownGraph = graph
    }
  }

  private fun fitTo(knots: Collection<Knot>, animated: Boolean) {
    if (knots.size < 2) return
    val bounds =
      LatLngBounds.Builder()
        .apply { knots.forEach { include(LatLng(it.latitude, it.longitude)) } }
        .build()
    val update = CameraUpdateFactory.newLatLngBounds(bounds, 160)
    if (animated) map?.animateCamera(update) else map?.moveCamera(update)
  }

  private fun addLayers(style: Style) {
    // Problems are dark on the light map and light on the dark map, never red, so they never read
    // like a German knot, see `map-planning` "Route knots stand out".
    val dark = styleDark == true
    val problem = if (dark) PROBLEM_ON_DARK else PROBLEM_ON_LIGHT
    val casing = if (dark) PROBLEM_ON_LIGHT else "#FFFFFF"
    listOf(
        "connections",
        "marker",
        "ridden-track",
        "route",
        "route-ahead",
        "route-point-ways",
        "way-to-route",
        "guided-way",
        "next-knot",
        "route-knots",
        "offer",
        "knots",
        "my-position",
        "position",
      )
      .forEach {
        style.addSource(GeoJsonSource(it))
      }
    style.addImage("route-arrow", arrowBitmap())
    style.addImage(
      "rider-arrow",
      riderArrowBitmap(android.graphics.Color.parseColor(POSITION_BLUE)),
    )
    // The chosen search hit, drawn under route and knots, so it never hides a knot.
    style.addLayer(
      CircleLayer("marker", "marker")
        .withProperties(
          PropertyFactory.circleRadius(12f),
          PropertyFactory.circleColor(problem),
          PropertyFactory.circleStrokeColor(casing),
          PropertyFactory.circleStrokeWidth(3f),
        )
    )
    style.addLayer(
      LineLayer("connections", "connections")
        .withProperties(
          PropertyFactory.lineColor(GREEN),
          PropertyFactory.lineWidth(2f),
          PropertyFactory.lineOpacity(0.7f),
        )
    )
    style.addLayer(
      LineLayer("route", "route")
        .withFilter(Expression.eq(Expression.get("reachable"), true))
        .withProperties(
          PropertyFactory.lineColor(ORANGE),
          PropertyFactory.lineWidth(ROUTE_WIDTH),
          // To the right of the riding direction, so a stretch used both ways shows as two lines,
          // see `map-planning` "Route used in both directions".
          PropertyFactory.lineOffset(ROUTE_OFFSET),
          PropertyFactory.lineCap(Property.LINE_CAP_ROUND),
          PropertyFactory.lineJoin(Property.LINE_JOIN_ROUND),
        )
    )
    style.addLayer(
      LineLayer("route-unreachable", "route")
        .withFilter(Expression.eq(Expression.get("reachable"), false))
        .withProperties(
          PropertyFactory.lineColor(problem),
          PropertyFactory.lineWidth(4f),
          PropertyFactory.lineDasharray(arrayOf(2f, 2f)),
        )
    )
    // Arrows along the route show the riding direction: each leg runs from its start to its end.
    style.addLayer(
      SymbolLayer("route-direction", "route")
        .withFilter(Expression.eq(Expression.get("reachable"), true))
        .withProperties(
          PropertyFactory.symbolPlacement(Property.SYMBOL_PLACEMENT_LINE),
          PropertyFactory.symbolSpacing(48f),
          PropertyFactory.iconImage("route-arrow"),
          PropertyFactory.iconSize(ARROW_SIZE),
          PropertyFactory.iconOffset(ARROW_OFFSET),
          PropertyFactory.iconAllowOverlap(true),
          PropertyFactory.iconIgnorePlacement(true),
        )
    )
    // The ways of route points over the route: dots along paths, long dashes where only a straight
    // line is known, see `map-planning` "The line on the map".
    style.addLayer(
      LineLayer("route-point-ways", "route-point-ways")
        .withFilter(Expression.eq(Expression.get("straight"), false))
        .withProperties(
          PropertyFactory.lineColor("#FFFFFF"),
          PropertyFactory.lineWidth(2.5f),
          PropertyFactory.lineDasharray(arrayOf(0.1f, 2f)),
          PropertyFactory.lineCap(Property.LINE_CAP_ROUND),
        )
    )
    style.addLayer(
      LineLayer("route-point-straight", "route-point-ways")
        .withFilter(Expression.eq(Expression.get("straight"), true))
        .withProperties(
          PropertyFactory.lineColor("#FFFFFF"),
          PropertyFactory.lineWidth(2.5f),
          PropertyFactory.lineDasharray(arrayOf(3f, 3f)),
        )
    )
    // While navigating, the course to the next knot, see `knot-navigation` "Leg ahead on the map".
    style.addLayer(
      LineLayer("route-ahead", "route-ahead")
        .withProperties(
          PropertyFactory.lineColor(ORANGE),
          PropertyFactory.lineWidth(ROUTE_WIDTH_AHEAD),
          PropertyFactory.lineOffset(ROUTE_OFFSET),
          PropertyFactory.lineCap(Property.LINE_CAP_ROUND),
          PropertyFactory.lineJoin(Property.LINE_JOIN_ROUND),
        )
    )
    style.addLayer(
      SymbolLayer("route-ahead-direction", "route-ahead")
        .withProperties(
          PropertyFactory.symbolPlacement(Property.SYMBOL_PLACEMENT_LINE),
          PropertyFactory.symbolSpacing(48f),
          PropertyFactory.iconImage("route-arrow"),
          PropertyFactory.iconSize(ARROW_SIZE),
          PropertyFactory.iconOffset(ARROW_OFFSET),
          PropertyFactory.iconAllowOverlap(true),
          PropertyFactory.iconIgnorePlacement(true),
        )
    )
    // On top of the route and its arrows, half as wide: the ridden part shows blue with the route's
    // orange at its edges, see `knot-navigation` "Ridden track".
    style.addLayer(
      LineLayer("ridden-track", "ridden-track")
        .withProperties(
          PropertyFactory.lineColor(TRACK_BLUE),
          PropertyFactory.lineWidth(TRACK_WIDTH),
          PropertyFactory.lineOffset(ROUTE_OFFSET),
          PropertyFactory.lineCap(Property.LINE_CAP_ROUND),
          PropertyFactory.lineJoin(Property.LINE_JOIN_ROUND),
        )
    )
    style.addLayer(
      SymbolLayer("knots", "knots")
        .withProperties(
          PropertyFactory.iconImage(
            Expression.concat(Expression.literal("knot-"), Expression.get("ref"))
          ),
          PropertyFactory.iconAllowOverlap(true),
          PropertyFactory.iconIgnorePlacement(true),
        )
        .apply { minZoom = KNOT_MIN_ZOOM.toFloat() }
    )
    style.addLayer(
      LineLayer("way-to-route-casing", "way-to-route")
        .withProperties(
          PropertyFactory.lineColor(casing),
          PropertyFactory.lineWidth(7f),
          PropertyFactory.lineDasharray(arrayOf(2f * 4 / 7, 2f * 4 / 7)),
          PropertyFactory.lineCap(Property.LINE_CAP_ROUND),
        )
    )
    style.addLayer(
      LineLayer("way-to-route", "way-to-route")
        .withProperties(
          PropertyFactory.lineColor(problem),
          PropertyFactory.lineWidth(4f),
          PropertyFactory.lineDasharray(arrayOf(2f, 2f)),
          PropertyFactory.lineCap(Property.LINE_CAP_ROUND),
        )
    )
    style.addLayer(
      LineLayer("guided-way-casing", "guided-way")
        .withProperties(
          PropertyFactory.lineColor(casing),
          PropertyFactory.lineWidth(8f),
          PropertyFactory.lineCap(Property.LINE_CAP_ROUND),
          PropertyFactory.lineJoin(Property.LINE_JOIN_ROUND),
        )
    )
    style.addLayer(
      LineLayer("guided-way", "guided-way")
        .withProperties(
          PropertyFactory.lineColor(problem),
          PropertyFactory.lineWidth(5f),
          PropertyFactory.lineCap(Property.LINE_CAP_ROUND),
          PropertyFactory.lineJoin(Property.LINE_JOIN_ROUND),
        )
    )
    // The position found on request while planning: a dot that does not follow the rider.
    style.addLayer(
      CircleLayer("my-position", "my-position")
        .withProperties(
          PropertyFactory.circleRadius(8f),
          PropertyFactory.circleColor(POSITION_BLUE),
          PropertyFactory.circleStrokeColor("#FFFFFF"),
          PropertyFactory.circleStrokeWidth(3f),
        )
    )
    // The next knot while navigating: a ring under its badge.
    style.addLayer(
      CircleLayer("next-knot", "next-knot")
        .withProperties(
          PropertyFactory.circleRadius(26f),
          PropertyFactory.circleColor(ORANGE),
          PropertyFactory.circleOpacity(0.35f),
          PropertyFactory.circleStrokeColor(ORANGE),
          PropertyFactory.circleStrokeWidth(3f),
        )
    )
    // Route knots are drawn above the network's knots, with a badge per role.
    style.addLayer(
      SymbolLayer("route-knots", "route-knots")
        .withProperties(
          PropertyFactory.iconImage(
            Expression.concat(
              Expression.literal("route-"),
              Expression.get("role"),
              Expression.literal("-"),
              Expression.get("plate"),
              Expression.literal("-"),
              Expression.get("ref"),
              Expression.literal("-"),
              Expression.get("place"),
            )
          ),
          PropertyFactory.iconAllowOverlap(true),
          PropertyFactory.iconIgnorePlacement(true),
        )
        .apply { minZoom = KNOT_MIN_ZOOM.toFloat() }
    )
    // The tapped place while its choices are shown: a flag in a white badge, above the route, so it
    // is clear where a route point would go, see `map-planning` "Choose a route point on the map".
    style.addImage("offer-flag", badgeBitmap(null, ""))
    style.addLayer(
      SymbolLayer("offer", "offer")
        .withProperties(
          PropertyFactory.iconImage("offer-flag"),
          PropertyFactory.iconSize(1.4f),
          PropertyFactory.iconAllowOverlap(true),
          PropertyFactory.iconIgnorePlacement(true),
        )
    )
    // The rider's position while navigating, above everything else.
    style.addLayer(
      CircleLayer("position", "position")
        .withFilter(Expression.not(Expression.has("direction")))
        .withProperties(
          // 30 dp across with the outline, see `knot-navigation` "Riding direction on the map".
          PropertyFactory.circleRadius(12f),
          PropertyFactory.circleColor(POSITION_BLUE),
          PropertyFactory.circleStrokeColor("#FFFFFF"),
          PropertyFactory.circleStrokeWidth(3f),
        )
    )
    style.addLayer(
      SymbolLayer("position-arrow", "position")
        .withFilter(Expression.has("direction"))
        .withProperties(
          PropertyFactory.iconImage("rider-arrow"),
          PropertyFactory.iconRotate(Expression.get("direction")),
          PropertyFactory.iconRotationAlignment(Property.ICON_ROTATION_ALIGNMENT_MAP),
          // The bitmap is drawn at the display's density: scaled to an arrow RIDER_ARROW_DP long.
          PropertyFactory.iconSize(RIDER_ARROW_DP * density / RIDER_ARROW_PIXELS),
          PropertyFactory.iconAllowOverlap(true),
          PropertyFactory.iconIgnorePlacement(true),
        )
    )
