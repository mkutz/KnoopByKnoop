  private fun updateNavigation(style: Style) {
    fun point(latitude: Double, longitude: Double) =
      """{"type": "Point", "coordinates": [$longitude, $latitude]}"""
    val empty = """{"type": "FeatureCollection", "features": []}"""
    // With a riding direction, the position is drawn as an arrow rotated by it, see
    // `knot-navigation` "Riding direction on the map".
    style
      .getSourceAs<GeoJsonSource>("position")
      ?.setGeoJson(
        position?.let { fix ->
          val properties = direction?.let { """"direction": $it""" } ?: ""
          """{"type": "Feature", "properties": {$properties}, "geometry": ${point(fix.latitude, fix.longitude)}}"""
        } ?: empty
      )
    style
      .getSourceAs<GeoJsonSource>("next-knot")
      ?.setGeoJson(
        // At each of its signposts, see `map-planning` "Knots signposted at several places".
        nextKnot?.let { knot ->
          val coordinates = knot.positions.joinToString(",") { "[${it.longitude}, ${it.latitude}]" }
          """{"type": "MultiPoint", "coordinates": [$coordinates]}"""
        } ?: empty
      )
    // Off route, the straight way back to the route, see `knot-navigation` "Way to the route on
    // the map".
    val fix = position
    val end = wayToRoute
    style
      .getSourceAs<GeoJsonSource>("way-to-route")
      ?.setGeoJson(
        if (fix != null && end != null && guidedWay == null)
          """{"type": "LineString", "coordinates": [[${fix.longitude}, ${fix.latitude}], [${end.longitude}, ${end.latitude}]]}"""
        else empty
      )
    val way = guidedWay
    style
      .getSourceAs<GeoJsonSource>("guided-way")
      ?.setGeoJson(
        if (way != null)
          way.joinToString(
            ",",
            """{"type": "LineString", "coordinates": [""",
            "]}",
          ) {
            "[${it.longitude}, ${it.latitude}]"
          }
        else empty
      )
  }

