"""Generates the app icons of both apps from one geometry.

Run from the repository root (needs Inkscape and ImageMagick):

    python3 design/icon/generate.py

Writes the source SVGs to design/icon/, the iOS app icon and launch logo to the asset catalog and
the Android adaptive icon to the app's resources. The motif is a path through knots, ending in the next knot.
"""

import json
import pathlib
import subprocess
import tempfile

ROOT = pathlib.Path(__file__).resolve().parents[2]
DESIGN = ROOT / "design" / "icon"
IOS_ICON_SET = ROOT / "apps/ios/KnoopByKnoop/Assets.xcassets/AppIcon.appiconset"
IOS_LAUNCH_LOGO = ROOT / "apps/ios/KnoopByKnoop/Assets.xcassets/LaunchLogo.imageset"
# The launch logo's size in points, like the icon on Android's splash screen.
LAUNCH_LOGO_POINTS = 192
ANDROID_RES = ROOT / "apps/android/src/main/res"

GREEN = "#2E9E5B"
ORANGE = "#F28C28"
WHITE = "#FFFFFF"
GRAY = "#8E8E93"

# The motif in a 1024 × 1024 box. Its bounding box is centered at CENTER.
LINE = [(250, 790), (455, 650), (360, 450), (506, 400)]
LINE_WIDTH = 44
KNOT_RADIUS = 58
NEXT_KNOT = (680, 340)
NEXT_KNOT_RADIUS = 168
RING_WIDTH = 32
ARROW = "M600,420 L752,268 M652,262 L758,262 L758,368"
ARROW_WIDTH = 44
CENTER = (528, 502)


def circle_path(center, radius):
    x, y = center
    return f"M{x - radius},{y} a{radius},{radius} 0 1,0 {2 * radius},0 a{radius},{radius} 0 1,0 {-2 * radius},0"


LINE_PATH = "M" + " L".join(f"{x},{y}" for x, y in LINE)
KNOTS_PATH = " ".join(circle_path(point, KNOT_RADIUS) for point in LINE[:3])
NEXT_KNOT_PATH = circle_path(NEXT_KNOT, NEXT_KNOT_RADIUS)


def svg(background, foreground, accent, arrow, round=False):
    """An iOS icon: full bleed and square, the system rounds the corners. Round for the launch logo."""
    offset_x, offset_y = 512 - CENTER[0], 512 - CENTER[1]
    if not background:
        background_rect = ""
    elif round:
        background_rect = f'<circle cx="512" cy="512" r="512" fill="{background}"/>'
    else:
        background_rect = f'<rect width="1024" height="1024" fill="{background}"/>'
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" width="1024" height="1024">
  {background_rect}
  <g transform="translate({offset_x},{offset_y})" stroke-linecap="round" stroke-linejoin="round">
    <path d="{LINE_PATH}" fill="none" stroke="{foreground}" stroke-width="{LINE_WIDTH}"/>
    <path d="{KNOTS_PATH}" fill="{foreground}"/>
    <path d="{NEXT_KNOT_PATH}" fill="{accent}" stroke="{foreground}" stroke-width="{RING_WIDTH}"/>
    <path d="{ARROW}" fill="none" stroke="{arrow}" stroke-width="{ARROW_WIDTH}"/>
  </g>
</svg>
"""


# Android adaptive icons are 108 dp; the mask shows about 72 dp. The motif takes the same share
# of the visible area as on iOS and stays well inside the 66 dp safe zone.
ANDROID_SCALE = 0.07
ANDROID_TRANSLATE = (54 - CENTER[0] * ANDROID_SCALE, 54 - CENTER[1] * ANDROID_SCALE)


def android_vector(paths):
    elements = "\n".join(f"    {path}" for path in paths)
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by design/icon/generate.py, do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
  android:width="108dp"
  android:height="108dp"
  android:viewportWidth="108"
  android:viewportHeight="108">
  <group
    android:scaleX="{ANDROID_SCALE}"
    android:scaleY="{ANDROID_SCALE}"
    android:translateX="{ANDROID_TRANSLATE[0]:.2f}"
    android:translateY="{ANDROID_TRANSLATE[1]:.2f}">
{elements}
  </group>
</vector>
"""


def stroke(path, color, width, fill=None):
    fill_attribute = f' android:fillColor="{fill}"' if fill else ""
    return (
        f'<path android:pathData="{path}"{fill_attribute} android:strokeColor="{color}" '
        f'android:strokeWidth="{width}" android:strokeLineCap="round" android:strokeLineJoin="round"/>'
    )


def fill(path, color):
    return f'<path android:pathData="{path}" android:fillColor="{color}"/>'


def render(svg_file, png_file, opaque, size=1024):
    subprocess.run(
        ["inkscape", str(svg_file), "--export-type=png", f"--export-filename={png_file}", "-w", str(size), "-h", str(size)],
        check=True,
        capture_output=True,
    )
    if opaque:
        # The App Store rejects app icons with an alpha channel.
        subprocess.run(["magick", str(png_file), "-alpha", "off", str(png_file)], check=True)


def main():
    variants = {
        # The system adds its own dark background and tint, so those variants are transparent.
        "icon": svg(GREEN, WHITE, ORANGE, WHITE),
        "icon-dark": svg(None, WHITE, ORANGE, WHITE),
        "icon-tinted": svg(None, WHITE, GRAY, WHITE),
    }
    IOS_ICON_SET.mkdir(parents=True, exist_ok=True)
    for name, content in variants.items():
        (DESIGN / f"{name}.svg").write_text(content)
        render(DESIGN / f"{name}.svg", IOS_ICON_SET / f"{name}.png", opaque=name == "icon")

    image = {"idiom": "universal", "platform": "ios", "size": "1024x1024"}
    images = [
        {"filename": "icon.png", **image},
        {"appearances": [{"appearance": "luminosity", "value": "dark"}], "filename": "icon-dark.png", **image},
        {"appearances": [{"appearance": "luminosity", "value": "tinted"}], "filename": "icon-tinted.png", **image},
    ]
    info = {"author": "xcode", "version": 1}
    (IOS_ICON_SET / "Contents.json").write_text(json.dumps({"images": images, "info": info}, indent=2) + "\n")
    (IOS_ICON_SET.parent / "Contents.json").write_text(json.dumps({"info": info}, indent=2) + "\n")

    # The launch screen shows the round icon, like Android's splash screen, see apps/ios/project.yml.
    (DESIGN / "launch-logo.svg").write_text(svg(GREEN, WHITE, ORANGE, WHITE, round=True))
    IOS_LAUNCH_LOGO.mkdir(parents=True, exist_ok=True)
    launch_images = []
    for scale in (1, 2, 3):
        filename = f"launch-logo@{scale}x.png"
        render(DESIGN / "launch-logo.svg", IOS_LAUNCH_LOGO / filename, opaque=False, size=LAUNCH_LOGO_POINTS * scale)
        launch_images.append({"filename": filename, "idiom": "universal", "scale": f"{scale}x"})
    (IOS_LAUNCH_LOGO / "Contents.json").write_text(json.dumps({"images": launch_images, "info": info}, indent=2) + "\n")

    drawables = ANDROID_RES / "drawable"
    drawables.mkdir(parents=True, exist_ok=True)
    (drawables / "ic_launcher_foreground.xml").write_text(
        android_vector(
            [
                stroke(LINE_PATH, WHITE, LINE_WIDTH),
                fill(KNOTS_PATH, WHITE),
                stroke(NEXT_KNOT_PATH, WHITE, RING_WIDTH, fill=ORANGE),
                stroke(ARROW, WHITE, ARROW_WIDTH),
            ]
        )
    )
    # Themed icons tint this single-color layer, so the next knot is a ring around the arrow.
    (drawables / "ic_launcher_monochrome.xml").write_text(
        android_vector(
            [
                stroke(LINE_PATH, "#000000", LINE_WIDTH),
                fill(KNOTS_PATH, "#000000"),
                stroke(NEXT_KNOT_PATH, "#000000", RING_WIDTH + 8),
                stroke(ARROW, "#000000", ARROW_WIDTH),
            ]
        )
    )
    values = ANDROID_RES / "values"
    values.mkdir(parents=True, exist_ok=True)
    (values / "ic_launcher_background.xml").write_text(
        f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by design/icon/generate.py, do not edit. -->
<resources>
  <color name="ic_launcher_background">{GREEN}</color>
</resources>
"""
    )
    adaptive_icon = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by design/icon/generate.py, do not edit. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
  <background android:drawable="@color/ic_launcher_background" />
  <foreground android:drawable="@drawable/ic_launcher_foreground" />
  <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
"""
    mipmaps = ANDROID_RES / "mipmap-anydpi"
    mipmaps.mkdir(parents=True, exist_ok=True)
    (mipmaps / "ic_launcher.xml").write_text(adaptive_icon)
    (mipmaps / "ic_launcher_round.xml").write_text(adaptive_icon)


if __name__ == "__main__":
    main()
